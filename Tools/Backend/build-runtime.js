// Build the single ES5 bundle uploaded to Nakama. No dependencies/network.
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'../..'),dir=path.join(root,'Backend/NakamaRuntime');
const sources=['index.core.js','mega-pot-rules.js','hot-streak-rules.js','economy-domain.js','economy-settlement.js'];
const bundle='// GENERATED by node Tools/Backend/build-runtime.js. Edit the source modules.\n'+sources.map(name=>'\n// ---- '+name+' ----\n'+fs.readFileSync(path.join(dir,name),'utf8')).join('\n');
const target=path.join(dir,'index.js');
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==bundle)throw Error('Runtime bundle is stale');}
else fs.writeFileSync(target,bundle);
console.log('Runtime bundle '+(process.argv.includes('--check')?'verified':'built')+'.');
